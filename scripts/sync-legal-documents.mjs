import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const terms = await readFile(new URL('TERMS_OF_SERVICE.md', root), 'utf8');
const privacy = await readFile(new URL('PRIVACY_POLICY.md', root), 'utf8');
const targetDirectory = new URL('src/legal/', root);
await mkdir(targetDirectory, { recursive: true });
await writeFile(new URL('legal-documents.ts', targetDirectory),
  `// Generated by scripts/sync-legal-documents.mjs from the complete root legal drafts.\n` +
  `export const termsOfServiceMarkdown = ${JSON.stringify(terms)};\n` +
  `export const privacyPolicyMarkdown = ${JSON.stringify(privacy)};\n`, 'utf8');
console.log('Synced the complete Terms and Privacy drafts into the app.');
